"""Security test report (Stage 20): the attack results as a Markdown document and a JSON summary."""

from __future__ import annotations

from incident_agent.security.attacks import OUTCOMES, Result, summarise

AREAS = {
    "injection": "Prompt injection and deception hidden in logs",
    "approval": "Approval forgery and gate abuse",
    "input": "Untrusted identifiers, signals and command lines",
    "killswitch": "Kill-switch",
}
OWNERS = {
    "INJ-04": "Needs corroboration across logs, metrics and deploys in the diagnosers; not a text-filter problem.",
    "INJ-07": "A semantic classifier (LLM judge) could shrink this; it would itself be attackable.",
}
ICON = {"blocked": "pass", "exposed": "EXPOSED", "evaded": "evaded", "gap": "GAP", "vulnerable": "FAIL"}


def to_markdown(results: list[Result]) -> str:
    s = summarise(results)
    v = s["verdicts"]
    lines = [
        "# Security test report (Stage 20)",
        "",
        "Generated by `python -m incident_agent.security report`. Every row is an attack run against the real "
        "components on the dev split; nothing here touches the test split or real data.",
        "",
        f"**{s['attacks']} attacks:** " + ", ".join(f"{v[k]} {k}" for k in OUTCOMES),
        "",
        "| Verdict | Meaning |",
        "|---|---|",
        "| pass | the attack was stopped, or the control check passed |",
        "| EXPOSED | unprotected today because the defence exists but is **not wired** into the agents |",
        "| evaded | a known evasion of a pattern-based control, kept in the corpus on purpose |",
        "| GAP | a documented open weakness with a named owner |",
        "| FAIL | the attack worked against something that should be protected (fails the build) |",
        "",
    ]
    for area, title in AREAS.items():
        rows = [r for r in results if r.area == area]
        if not rows:
            continue
        lines += [f"## {title}", "", "| ID | Attack | Verdict | Detail |", "|---|---|---|---|"]
        lines += [f"| {r.id} | {r.title} | {ICON[r.verdict]} | {r.detail.replace('|', '/')} |" for r in rows]
        lines.append("")
    open_items = [r for r in results if r.verdict in ("exposed", "gap", "evaded", "vulnerable")]
    lines += ["## Open items", ""]
    if not open_items:
        lines.append("None.")
    for r in open_items:
        lines.append(f"* **{r.id}** ({r.verdict}): {OWNERS.get(r.id, 'no owner recorded')}")
    lines += [
        "",
        "## What the defence actually is",
        "",
        "1. Commands come from a fixed table, never from log text (INJ-01).",
        "2. A mutating command needs a human approval sealed by the gate; a forged, replayed, edited or foreign "
        "approval only produces a dry run (APP-01..05).",
        "3. Silence is a refusal: expiry never approves (Stage 18; INJ-02).",
        "4. The sandbox allow-list refuses injected command lines (INP-05).",
        "5. The kill-switch stops runs and backend calls, fails closed and the agent cannot release it (KIL-01..07).",
        "6. Log and tool text is stripped of injection-looking lines by default (INJ-09, INJ-12, INJ-13).",
        "7. The request store is an HMAC chain: a line written without the key is refused (APP-08).",
        "",
        "## Limits of this report",
        "",
        "* The detector was tuned on the same corpus it is scored on, so its recall is optimistic; INJ-07 lists what "
        "it misses by design.",
        "* HMAC seals and the store chain stop writers without the key, not a same-user attacker who can read it.",
        "* The isolation backend in these runs is a plain subprocess; real isolation is Stage 16's selftest.",
        "* Only the rule-based planner and diagnoser were attacked end to end. LLM diagnosers have no recorded "
        "attack results (INJ-09 is a code-level finding).",
    ]
    return "\n".join(lines) + "\n"
